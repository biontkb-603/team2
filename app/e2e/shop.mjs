import { launch, BASE, OUT } from './lib.mjs'
const b = await launch()
const p = await b.newPage(); await p.setViewport({ width: 408, height: 880 })
const base = BASE, wait = ms => new Promise(r => setTimeout(r, ms))
let fail = 0; const ok = (c, m) => { if (!c) { fail++; console.log('FAIL', m) } }
await p.goto(base + '/shopping', { waitUntil: 'networkidle0' }); await p.screenshot({ path: OUT + '/sp.png' })
ok((await p.$$eval('nav a', as => as.filter(a => a.className.includes('text-primary')).map(a => a.textContent))).join() === '장보기', 'tab active')
const links = () => p.$$eval('ul a', l => l.map(a => ({ name: a.textContent.trim(), href: a.href, target: a.target, rel: a.rel })))
let l = await links()
ok(l.map(x => x.name).join('|') === '쿠쿠팡|네네이버 스토어|컬마켓컬리|이이마트몰', 'mall names ' + l.map(x => x.name))
ok(l.every(x => x.target === '_blank' && x.rel.includes('noopener')), 'new tab + noopener')
ok(l[0].href === 'https://www.coupang.com/' , 'empty keyword -> home ' + l[0].href)
await p.type('input[aria-label="재료 이름 검색"]', '김가루'); l = await links()
ok(l[0].href === 'https://www.coupang.com/np/search?q=%EA%B9%80%EA%B0%80%EB%A3%A8', 'coupang search ' + l[0].href)
ok(l[1].href.includes('search.shopping.naver.com') && l[2].href.includes('kurly.com/search') && l[3].href.includes('emart.ssg.com/search.ssg'), 'all 4 search urls')
await p.click('button[aria-label="장바구니"]'); await wait(150); ok((await p.$eval('[role=status]', e => e.textContent)) === '곧 지원 예정이에요', 'cart toast')
await wait(2100)
const btn = await p.evaluateHandle(() => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === '장바구니에 담기')); await btn.click(); await wait(150)
ok((await p.$eval('[role=status]', e => e.textContent)) === '곧 지원 예정이에요', 'add-to-cart toast')
const bottom = await p.evaluate(() => { const t = document.querySelector('nav[aria-label="하단 탭"]').getBoundingClientRect().top; const r = [...document.querySelectorAll('button')].find(b => b.textContent.trim() === '장바구니에 담기').getBoundingClientRect(); return [r.bottom, t] })
ok(bottom[0] <= bottom[1], 'cart button above tab bar ' + bottom)
console.log(fail ? fail + ' failures' : 'ALL PASS'); process.exitCode = fail ? 1 : 0; await b.close()
